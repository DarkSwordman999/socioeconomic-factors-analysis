import pandas as pd
import numpy as np
import statsmodels.api as sm
from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error
from scripts.load_data import load_and_prepare_data

def investigate_models():
    """
    Исследование моделей и их перестроение при необходимости
    """
    print("=" * 80)
    print("ЛАБОРАТОРНАЯ РАБОТА D (продолжение)")
    print("Исследование выбранной модели и перестроение")
    print("=" * 80)
    
    df = load_and_prepare_data()
    
    # Исходные факторы
    X_full = df[['ВРП', 'Инвестиции', 'Доходы']]
    X_full = sm.add_constant(X_full)
    
    # Из-за мультиколлинеарности (корреляция ВРП и инвестиций = 0.91)
    # попробуем исключить инвестиции
    X_reduced = df[['ВРП', 'Доходы']]
    X_reduced = sm.add_constant(X_reduced)
    
    targets = {
        'Продолжительность_жизни': 'Ожидаемая продолжительность жизни (лет)',
        'Уровень_бедности': 'Уровень бедности (%)',
        'Жилплощадь': 'Жилплощадь на человека (кв.м)'
    }
    
    print("\n1. ПЕРЕСТРОЕНИЕ МОДЕЛЕЙ (ИСКЛЮЧЕНИЕ ИНВЕСТИЦИЙ)")
    print("=" * 60)
    
    for target_col, target_name in targets.items():
        y = df[target_col]
        
        # Исходная модель
        model_full = sm.OLS(y, X_full).fit()
        
        # Упрощённая модель (без инвестиций)
        model_reduced = sm.OLS(y, X_reduced).fit()
        
        print(f"\n{'='*50}")
        print(f"Модель: {target_name}")
        print(f"{'='*50}")
        print(f"\nИсходная модель (ВРП + Инвестиции + Доходы):")
        print(f"  R² = {model_full.rsquared:.4f}")
        print(f"  R²_adj = {model_full.rsquared_adj:.4f}")
        print(f"  MAPE = {np.mean(np.abs((y - model_full.fittedvalues)/y))*100:.2f}%")
        
        print(f"\nУпрощённая модель (ВРП + Доходы):")
        print(f"  R² = {model_reduced.rsquared:.4f}")
        print(f"  R²_adj = {model_reduced.rsquared_adj:.4f}")
        print(f"  MAPE = {np.mean(np.abs((y - model_reduced.fittedvalues)/y))*100:.2f}%")
        
        # Сравнение качества
        r2_diff = model_reduced.rsquared - model_full.rsquared
        if abs(r2_diff) < 0.01:
            print(f"\nВывод: Упрощённая модель имеет практически такое же качество")
            print(f"  (изменение R² = {r2_diff:.4f})")
            print(f"  Рекомендуется использовать упрощённую модель")
        else:
            print(f"\nВывод: Исходная модель показывает лучшее качество")
            print(f"  (изменение R² = {r2_diff:.4f})")
    
    print("\n2. ИССЛЕДОВАНИЕ ВЫБРАННОЙ МОДЕЛИ")
    print("=" * 60)
    
    # Выбираем лучшую модель (для уровня бедности)
    y = df['Уровень_бедности']
    X = df[['Доходы']]  # Доходы — самый значимый фактор
    X = sm.add_constant(X)
    model_best = sm.OLS(y, X).fit()
    
    print("\nВыбрана модель для анализа: Уровень бедности = f(Доходы)")
    print(f"\nУравнение: Уровень бедности = {model_best.params['const']:.4f} + {model_best.params['Доходы']:.8f}·Доходы")
    print(f"R² = {model_best.rsquared:.4f}")
    print(f"p-value коэффициента = {model_best.pvalues['Доходы']:.4e}")
    
    print("\nИНТЕРПРЕТАЦИЯ РЕЗУЛЬТАТОВ:")
    print("-" * 40)
    print(f"  При увеличении доходов на 1000 руб., уровень бедности")
    print(f"  снижается в среднем на {abs(model_best.params['Доходы'] * 1000):.4f}%")
    
    print("\n3. ОБЩИЕ ВЫВОДЫ ПО ЛАБОРАТОРНОЙ РАБОТЕ CD")
    print("=" * 60)
    print("""
    1. Построены модели множественной линейной регрессии для трёх социальных
       показателей (продолжительность жизни, уровень бедности, жилплощадь)
    
    2. Выявлено, что доходы населения — наиболее значимый фактор,
       влияющий на социальные показатели
    
    3. Обнаружена проблема мультиколлинеарности между ВРП и инвестициями
       (коэффициент корреляции = 0.91)
    
    4. При перестроении моделей (исключение инвестиций) качество моделей
       практически не изменилось, что подтверждает наличие мультиколлинеарности
    
    5. Рекомендуемая модель для практического использования:
       Уровень бедности = f(Доходы) — самая интерпретируемая и устойчивая
    
    6. Низкие значения R² (0.33-0.41) объясняются тем, что социальные
       показатели зависят не только от экономических факторов, но и от:
       - качества здравоохранения
       - экологической ситуации
       - эффективности социальной политики
       - демографической структуры населения
    """)
    
    return model_best

if __name__ == "__main__":
    model = investigate_models()

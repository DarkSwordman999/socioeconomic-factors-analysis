"""
Лабораторная работа D
Анализ качества модели
"""

import pandas as pd
import numpy as np
import statsmodels.api as sm
from sklearn.metrics import mean_absolute_error, mean_squared_error
from scripts.load_data import load_and_prepare_data

def quality_analysis():
    """
    Анализ качества моделей
    """
    print("=" * 80)
    print("Анализ качества модели")
    print("=" * 80)
    
    print("\n1. КРИТЕРИИ КАЧЕСТВА МОДЕЛИ")
    print("-" * 50)
    print("""
    Качество регрессионной модели оценивается по следующим критериям:
    
    1. Коэффициент детерминации R²:
       R² = 1 - Σ(y_i - ŷ_i)² / Σ(y_i - ȳ)²
       Показывает долю дисперсии зависимой переменной, объяснённую моделью.
       Чем ближе к 1, тем лучше.
    
    2. Скорректированный R²_adj:
       Учитывает количество факторов в модели.
    
    3. F-критерий Фишера:
       Проверяет значимость модели в целом.
       H₀: все коэффициенты равны нулю.
       Если p-value < 0.05, модель значима.
    
    4. t-критерий Стьюдента:
       Проверяет значимость отдельных коэффициентов.
       Если p-value < 0.05, коэффициент значим.
    
    5. Средняя абсолютная ошибка (MAE):
       MAE = (1/n) Σ|y_i - ŷ_i|
       Средняя ошибка в единицах измерения.
    
    6. Корень из среднеквадратичной ошибки (RMSE):
       RMSE = √[(1/n) Σ(y_i - ŷ_i)²]
       Стандартное отклонение ошибок.
    
    7. Средняя абсолютная процентная ошибка (MAPE):
       MAPE = (1/n) Σ|(y_i - ŷ_i)/y_i| · 100%
       Оценка точности в процентах.
       <10% - высокая точность
       10-20% - хорошая точность
       20-50% - удовлетворительная
       >50% - неудовлетворительная
    """)
    
    df = load_and_prepare_data()
    X = df[['ВРП', 'Инвестиции', 'Доходы']]
    X = sm.add_constant(X)
    
    targets = {
        'Продолжительность_жизни': 'Ожидаемая продолжительность жизни (лет)',
        'Уровень_бедности': 'Уровень бедности (%)',
        'Жилплощадь': 'Жилплощадь на человека (кв.м)'
    }
    
    print("\n2. РАСЧЁТ КРИТЕРИЕВ КАЧЕСТВА")
    print("=" * 60)
    
    results = {}
    
    for target_col, target_name in targets.items():
        y = df[target_col]
        model = sm.OLS(y, X).fit()
        y_pred = model.predict(X)
        
        # Расчёт метрик
        residuals = y - y_pred
        mae = mean_absolute_error(y, y_pred)
        rmse = np.sqrt(mean_squared_error(y, y_pred))
        mape = np.mean(np.abs(residuals / y)) * 100
        
        results[target_name] = {
            'R2': model.rsquared,
            'R2_adj': model.rsquared_adj,
            'F_stat': model.fvalue,
            'F_pvalue': model.f_pvalue,
            'MAE': mae,
            'RMSE': rmse,
            'MAPE': mape,
            'const_pvalue': model.pvalues['const'],
            'ВРП_pvalue': model.pvalues['ВРП'],
            'Инвестиции_pvalue': model.pvalues['Инвестиции'],
            'Доходы_pvalue': model.pvalues['Доходы'],
            'model': model
        }
        
        print(f"\n{'='*50}")
        print(f"Модель: {target_name}")
        print(f"{'='*50}")
        print(f"  R² = {model.rsquared:.4f}")
        print(f"  R²_adj = {model.rsquared_adj:.4f}")
        print(f"  F-статистика = {model.fvalue:.2f} (p-value = {model.f_pvalue:.4e})")
        print(f"  MAE = {mae:.4f}")
        print(f"  RMSE = {rmse:.4f}")
        print(f"  MAPE = {mape:.2f}%")
        
        # Оценка точности
        if mape < 10:
            print(f"  Точность: ВЫСОКАЯ (MAPE < 10%)")
        elif mape < 20:
            print(f"  Точность: ХОРОШАЯ (MAPE = 10-20%)")
        elif mape < 50:
            print(f"  Точность: УДОВЛЕТВОРИТЕЛЬНАЯ (MAPE = 20-50%)")
        else:
            print(f"  Точность: НЕУДОВЛЕТВОРИТЕЛЬНАЯ (MAPE > 50%)")
    
    print("\n3. ВЫВОДЫ ПО ЧАСТИ D")
    print("-" * 50)
    print("""
    1. Все модели статистически значимы (p-value F-теста < 0.05)
    
    2. Наиболее качественная модель — для уровня бедности (R² = 0.4056)
       Наименее качественная — для продолжительности жизни (R² = 0.3333)
    
    3. Коэффициенты при доходах значимы во всех моделях (p-value < 0.05)
    
    4. Коэффициенты при инвестициях и ВРП частично незначимы
    
    5. Точность моделей по MAPE:
       - Продолжительность жизни: удовлетворительная (4-5%)
       - Уровень бедности: удовлетворительная (~30%)
       - Жилплощадь: хорошая (~15%)
    
    6. Низкие значения R² объясняются тем, что социальные показатели
       зависят не только от экономических факторов, но и от других
       (качество здравоохранения, экология, социальная политика и др.)
    """)
    
    return results

def check_multicollinearity(df):
    """
    Проверка на мультиколлинеарность
    """
    print("\n4. ПРОВЕРКА НА МУЛЬТИКОЛЛИНЕАРНОСТЬ")
    print("-" * 50)
    
    corr_matrix = df[['ВРП', 'Инвестиции', 'Доходы']].corr()
    print("Матрица корреляций между факторами:")
    print(corr_matrix)
    
    print("\nВывод по мультиколлинеарности:")
    if corr_matrix.loc['ВРП', 'Инвестиции'] > 0.7:
        print("  - Высокая корреляция между ВРП и инвестициями (0.91) -> возможна мультиколлинеарность")
    if corr_matrix.loc['ВРП', 'Доходы'] > 0.7:
        print("  - Высокая корреляция между ВРП и доходами (0.76) -> возможна мультиколлинеарность")
    print("  - Это объясняет незначимость некоторых коэффициентов")
    print("  - Рекомендуется: исключить один из коррелирующих факторов")

if __name__ == "__main__":
    results = quality_analysis()
    df = load_and_prepare_data()
    check_multicollinearity(df)

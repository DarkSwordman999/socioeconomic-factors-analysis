import pandas as pd
import numpy as np
from scripts.load_data import load_and_prepare_data

def model_selection():
    """
    Подбор модели с учётом дескриптивной статистики
    """
    print("=" * 80)
    print("ЛАБОРАТОРНАЯ РАБОТА C")
    print("Часть 1. Подбор и описание модели")
    print("=" * 80)
    
    # Загружаем данные для анализа
    df = load_and_prepare_data()
    
    print("\n1. ОБОСНОВАНИЕ ВЫБОРА МОДЕЛИ")
    print("-" * 50)
    
    # Рассчитываем корреляции для обоснования
    indicators = ['ВРП', 'Инвестиции', 'Доходы', 'Продолжительность_жизни', 'Уровень_бедности', 'Жилплощадь']
    corr_matrix = df[indicators].corr()
    
    print("\nНа основе дескриптивной статистики выявлено:")
    print(f"  - Сильная корреляция между ВРП и инвестициями: {corr_matrix.loc['ВРП', 'Инвестиции']:.3f}")
    print(f"  - Сильная корреляция между ВРП и доходами: {corr_matrix.loc['ВРП', 'Доходы']:.3f}")
    print(f"  - Умеренная корреляция между доходами и жилплощадью: {corr_matrix.loc['Доходы', 'Жилплощадь']:.3f}")
    print(f"  - Слабая корреляция экономических факторов с продолжительностью жизни")
    
    print("\nВыбран тип модели: МНОЖЕСТВЕННАЯ ЛИНЕЙНАЯ РЕГРЕССИЯ")
    print("Обоснование выбора:")
    print("  1. Цель исследования — изучить взаимосвязи между экономическими")
    print("     и социальными факторами (количественная оценка влияния)")
    print("  2. Имеется одна зависимая переменная (социальный показатель)")
    print("     и несколько независимых (экономические факторы)")
    print("  3. Между переменными предполагается линейная связь")
    print("  4. Модель позволяет оценить вклад каждого фактора")
    
    print("\n2. МАТЕМАТИЧЕСКОЕ ОПИСАНИЕ МОДЕЛИ")
    print("-" * 50)
    print("""
    Общий вид множественной линейной регрессии:
    
        Y = β₀ + β₁·X₁ + β₂·X₂ + β₃·X₃ + ε
    
    где:
        Y   - зависимая переменная (социальный показатель)
        X₁  - ВРП на душу населения (руб.)
        X₂  - Инвестиции на душу населения (руб.)
        X₃  - Среднедушевые денежные доходы (руб.)
        β₀  - свободный член (константа)
        β₁, β₂, β₃ - коэффициенты регрессии
        ε   - случайная ошибка (остаток)
    
    Оценка параметров модели производится методом наименьших квадратов (МНК):
    
        Σ(Y_i - Ŷ_i)² → min
    
    Для каждого социального показателя строится своя модель:
    
    Модель 1: Продолжительность жизни = f(ВРП, инвестиции, доходы)
    Модель 2: Уровень бедности = f(ВРП, инвестиции, доходы)
    Модель 3: Жилплощадь = f(ВРП, инвестиции, доходы)
    """)
    
    return corr_matrix

if __name__ == "__main__":
    corr = model_selection()
